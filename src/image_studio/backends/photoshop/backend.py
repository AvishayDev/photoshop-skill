"""Optional Adobe Photoshop backend (local desktop automation only).

Uses Photoshop's documented *local* scripting interfaces:

* Windows: COM automation (``Photoshop.Application``) via pywin32, calling
  ``DoJavaScriptFile`` with an ExtendScript (JSX) file.
* macOS: AppleScript ``do javascript file`` via ``osascript``.

No Adobe cloud API, account API or paid transaction is involved; it only
drives a Photoshop installation the user already licensed. It is *not*
required by any part of the toolkit.

Status: implemented against Adobe's scripting documentation but NOT verified
in CI (Photoshop cannot be installed there). ``status().verified`` is False.

Capabilities: export a layered PSD (raster layers with position, opacity,
visibility, blend mode, and layer masks baked into alpha) and import a PSD's
composite. Everything else continues to use the core engine.
"""

from __future__ import annotations

import json
import platform
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Any

from ...errors import BackendExecutionError, BackendUnavailableError, UnsupportedOperationError
from ..base import CAP_EXPORT_NATIVE, Backend, BackendStatus

PS_BLEND = {
    "normal": "NORMAL", "multiply": "MULTIPLY", "screen": "SCREEN", "overlay": "OVERLAY",
    "soft_light": "SOFTLIGHT", "hard_light": "HARDLIGHT", "darken": "DARKEN", "lighten": "LIGHTEN",
    "color_dodge": "COLORDODGE", "color_burn": "COLORBURN", "linear_dodge": "LINEARDODGE",
    "linear_burn": "LINEARBURN", "difference": "DIFFERENCE", "exclusion": "EXCLUSION", "subtract": "SUBTRACT",
    "divide": "DIVIDE", "hue": "HUE", "saturation": "SATURATION", "color": "COLORBLEND", "luminosity": "LUMINOSITY",
    "pass_through": "PASSTHROUGH",
}

JSX_TEMPLATE = r"""
// Generated by agent-image-studio. Data-only: the layer list below is JSON.
var spec = __SPEC__;
var prevUnits = app.preferences.rulerUnits;
app.preferences.rulerUnits = Units.PIXELS;
app.displayDialogs = DialogModes.NO;
var doc = app.documents.add(spec.width, spec.height, spec.resolution, spec.name, NewDocumentMode.RGB,
                            DocumentFill.TRANSPARENT);
function placeItems(items, container) {
  for (var i = items.length - 1; i >= 0; i--) {   // items are top -> bottom; build bottom-up
    var it = items[i];
    var layer;
    if (it.kind == "group") {
      layer = container.layerSets.add();
      placeItems(it.children, layer);
    } else {
      var src = app.open(new File(it.png));
      src.selection.selectAll();
      src.artLayers[0].copy();
      src.close(SaveOptions.DONOTSAVECHANGES);
      app.activeDocument = doc;
      layer = doc.paste();
      if (container != doc) { layer.move(container, ElementPlacement.INSIDE); }
      var b = layer.bounds;
      layer.translate(it.x - b[0].value, it.y - b[1].value);
    }
    layer.name = it.name;
    layer.opacity = it.opacity * 100;
    try { layer.blendMode = BlendMode[it.ps_blend]; } catch (e) {}
    layer.visible = it.visible;
  }
}
placeItems(spec.layers, doc);
if (doc.artLayers.length > 0) {
  try { doc.artLayers[doc.artLayers.length - 1].remove(); } catch (e) {}
}
var opts = new PhotoshopSaveOptions(); opts.layers = true;
doc.saveAs(new File(spec.output), opts, true);
doc.close(SaveOptions.DONOTSAVECHANGES);
app.preferences.rulerUnits = prevUnits;
"""


class PhotoshopBackend(Backend):
    name = "photoshop"

    def _platform(self) -> str:
        return platform.system()

    def status(self) -> BackendStatus:
        how = ("Optional. Requires a locally installed, licensed Adobe Photoshop. Windows: pip install pywin32. "
               "macOS: allow your terminal to control Photoshop (Automation permission).")
        system = self._platform()
        if system == "Windows":
            try:
                import win32com.client  # type: ignore  # noqa: F401
            except ImportError:
                return BackendStatus(self.name, False, detail="pywin32 not installed", missing=["pywin32"],
                                     how_to_enable=how, verified=False)
            try:
                import winreg  # type: ignore
                winreg.OpenKey(winreg.HKEY_CLASSES_ROOT, "Photoshop.Application")
            except OSError:
                return BackendStatus(self.name, False, detail="Photoshop COM server not registered",
                                     how_to_enable=how, verified=False)
            return BackendStatus(self.name, True, native_formats=["psd"], detail="COM automation", verified=False)
        if system == "Darwin":
            apps = sorted(Path("/Applications").glob("Adobe Photoshop*/Adobe Photoshop*.app"))
            if apps and shutil.which("osascript"):
                return BackendStatus(self.name, True, native_formats=["psd"], detail=f"AppleScript: {apps[-1].name}",
                                     verified=False)
            return BackendStatus(self.name, False, detail="Photoshop.app not found in /Applications",
                                 how_to_enable=how, verified=False)
        return BackendStatus(self.name, False, detail=f"Photoshop is not available on {system}",
                             how_to_enable="Photoshop automation is only possible on Windows and macOS.",
                             verified=False)

    def capabilities(self) -> set[str]:
        return {CAP_EXPORT_NATIVE}

    def build_jsx(self, spec: dict[str, Any], out_path: Path) -> str:
        def conv(items):
            out = []
            for it in items:
                d = {"name": it["name"], "kind": it.get("kind", "raster"), "x": int(it.get("x", 0)),
                     "y": int(it.get("y", 0)), "opacity": float(it.get("opacity", 1)),
                     "visible": bool(it.get("visible", True)),
                     "ps_blend": PS_BLEND.get(it.get("blend_mode", "normal"), "NORMAL")}
                if d["kind"] == "group":
                    d["children"] = conv(it.get("children", []))
                else:
                    d["kind"] = "raster"
                    d["png"] = str(it.get("png_masked") or it["png"]).replace("\\", "/")
                out.append(d)
            return out

        data = {"width": spec["width"], "height": spec["height"], "resolution": spec.get("resolution", 72),
                "name": spec.get("name", "document"), "layers": conv(spec["layers"]),
                "output": str(out_path).replace("\\", "/")}
        return JSX_TEMPLATE.replace("__SPEC__", json.dumps(data))

    def export_native(self, spec: dict[str, Any], out_path: Path, fmt: str) -> dict[str, Any]:
        if fmt != "psd":
            raise UnsupportedOperationError("Photoshop backend writes 'psd' only")
        st = self.status()
        if not st.available:
            raise BackendUnavailableError(f"Photoshop backend unavailable: {st.detail}", hint=st.how_to_enable)
        with tempfile.TemporaryDirectory(prefix="psjsx_") as d:
            jsx = Path(d) / "export.jsx"
            jsx.write_text(self.build_jsx(spec, out_path), encoding="utf-8")
            if self._platform() == "Windows":
                import win32com.client  # type: ignore
                app = win32com.client.Dispatch("Photoshop.Application")
                app.DoJavaScriptFile(str(jsx))
            else:
                script = f'tell application id "com.adobe.Photoshop" to do javascript file (POSIX file "{jsx}")'
                proc = subprocess.run(["osascript", "-e", script], capture_output=True, text=True, timeout=600)
                if proc.returncode != 0:
                    raise BackendExecutionError(f"Photoshop script failed: {proc.stderr.strip()[:500]}")
        if not out_path.exists():
            raise BackendExecutionError("Photoshop did not write the PSD")
        return {"format": "psd", "path": str(out_path),
                "warnings": ["Layer masks are baked into alpha in PSD export; text is rasterized."]}
